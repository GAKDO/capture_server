-- CA2 검사 결과 저장·시점 비교·등급 (specs/003-inspection-grading). docs design/ddl.md·db/V1__init.sql에도 같은 칸을 더했다.
-- 기본값은 이미 있는 행을 채우기 위해서만 주고 바로 지운다(앱이 늘 값을 넣는다).

-- 부스 탐지는 원본 사진 px로 받고(photo_polygon), 표준 좌표 polygon은 정합(trace.inspect.completed alignments) 뒤 채운다 (11/2)
ALTER TABLE inspection.defect ADD COLUMN photo_polygon jsonb NOT NULL DEFAULT '[]';
ALTER TABLE inspection.defect ALTER COLUMN photo_polygon DROP DEFAULT;
ALTER TABLE inspection.defect ALTER COLUMN polygon DROP NOT NULL;

-- 비교 규칙 버전(예: view-match-v1, 11/2)
ALTER TABLE inspection.defect_match ADD COLUMN rule_version varchar(32) NOT NULL DEFAULT 'view-match-v1';
ALTER TABLE inspection.defect_match ALTER COLUMN rule_version DROP DEFAULT;
CREATE INDEX ix_defect_match_prev ON inspection.defect_match(prev_defect_id);

-- 등급을 매긴 세트와 판정 불가 면(다음 시점 비교의 기준이 된다)
ALTER TABLE inspection.grade_result ADD COLUMN capture_set_id bigint REFERENCES capture.capture_set(id);
ALTER TABLE inspection.grade_result ADD COLUMN unjudgeable_faces jsonb NOT NULL DEFAULT '[]';

-- 부스 탐지를 받은 시각. 부스 세트는 정합과 탐지가 모두 와야 등급을 매긴다
ALTER TABLE capture.capture_set ADD COLUMN detections_received_at timestamptz;
CREATE INDEX ix_capture_set_rental ON capture.capture_set(rental_id);

-- 3D 트윈에 입힐 면별 텍스처(trace.inspect.completed textureKeys, 버킷 trace-derived). /media 보기 URL의 재료
CREATE TABLE inspection.face_texture (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  capture_set_id  bigint       NOT NULL REFERENCES capture.capture_set(id),
  face            varchar(4)   NOT NULL CHECK (face IN ('TOP','BOT','SF','SB','SL','SR','KB','SCR0','SCR1')),
  object_key      varchar(512) NOT NULL,
  created_at      timestamptz  NOT NULL DEFAULT now(),
  updated_at      timestamptz  NOT NULL DEFAULT now(),
  UNIQUE (capture_set_id, face)
);
