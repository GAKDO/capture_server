-- capture·inspection 스키마 초기화. 원본: GAKDO/docs db/V1__init.sql의 capture·inspection 절(design/ddl.md). 이 서버 스키마만 둔다.
-- 기본 키 id는 bigint(밖에 내보내지 않음), 밖에 보이는 ID는 public_id(NanoID 21자) (decisions.md 11/2, 헌법 1.1.0).
-- CA1에서 더한 칸(docs에도 반영): capture_set.rental_id·completion_*, photo.uploaded
CREATE SCHEMA IF NOT EXISTS capture;
CREATE SCHEMA IF NOT EXISTS inspection;

CREATE TABLE capture.capture_set (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id      varchar(21) NOT NULL UNIQUE,
  rental_id      varchar(21) NOT NULL,                -- rental.rental.public_id (FK 없음). 이벤트 봉투 rentalId (CA1)
  checkpoint_id  varchar(21) NOT NULL,                -- rental.checkpoint.public_id (FK 없음)
  source         varchar(8)  NOT NULL CHECK (source IN ('BOOTH','PHONE')),
  booth_id       varchar(32),
  status         varchar(16) NOT NULL CHECK (status IN ('UPLOADING','UPLOADED','INSPECTED','GRADED')),
  quality        varchar(16) NOT NULL DEFAULT 'OK' CHECK (quality IN ('OK','UNJUDGEABLE')),
  skipped_faces  jsonb       NOT NULL DEFAULT '{}',              -- 건너뛴 선택 면과 사유 {"SCR1": "사유"} (11/2)
  completion_key            varchar(128),   -- 완료 요청의 Idempotency-Key (CA1)
  completion_request_sha256 char(64),       -- 같은 키에 다른 본문인지 가리는 해시 (CA1)
  completion_response       jsonb,          -- 같은 키로 다시 오면 돌려줄 첫 응답 (CA1)
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_capture_set_checkpoint ON capture.capture_set(checkpoint_id);

CREATE TABLE capture.photo (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id       varchar(21) NOT NULL UNIQUE,
  capture_set_id  bigint NOT NULL REFERENCES capture.capture_set(id),
  face            varchar(4)   NOT NULL CHECK (face IN ('TOP','BOT','SF','SB','SL','SR','KB','SCR0','SCR1')),
  light           varchar(4)   NOT NULL CHECK (light IN ('L1','L2','L3','L4','ROOM','OFF')),
  camera          varchar(8)   NOT NULL CHECK (camera IN ('CAM1','CAM2','PHONE')),
  object_key      varchar(512) NOT NULL,
  sha256          char(64)     NOT NULL,
  uploaded        boolean      NOT NULL DEFAULT false,   -- 완료 때 저장소에서 존재·해시를 확인함 (CA1)
  blur_score      real,
  quality_ok      boolean      NOT NULL DEFAULT true,
  taken_at        timestamptz  NOT NULL,
  created_at      timestamptz  NOT NULL DEFAULT now(),
  updated_at      timestamptz  NOT NULL DEFAULT now(),
  UNIQUE (capture_set_id, face, light, camera)   -- 위 카메라 2대가 같은 면·조명을 찍음 (11/2)
);

CREATE TABLE inspection.face_alignment (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  photo_id       bigint NOT NULL UNIQUE REFERENCES capture.photo(id),
  method         varchar(16)  NOT NULL CHECK (method IN ('CONTOUR','LIGHTGLUE')),
  homography     jsonb        NOT NULL,
  error_px       real,
  rectified_key  varchar(512) NOT NULL,
  created_at     timestamptz  NOT NULL DEFAULT now(),
  updated_at     timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE inspection.defect (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id      varchar(21) NOT NULL UNIQUE,
  photo_id       bigint NOT NULL REFERENCES capture.photo(id),
  class          varchar(8)  NOT NULL CHECK (class IN ('scratch','dent','crack','stain')),
  polygon        jsonb       NOT NULL,
  length_mm      real,
  area_mm2       real,
  confidence     real        NOT NULL,
  model_version  varchar(64) NOT NULL,
  source         varchar(8)  NOT NULL DEFAULT 'AUTO' CHECK (source IN ('AUTO','HUMAN')),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_defect_photo ON inspection.defect(photo_id);

CREATE TABLE inspection.defect_match (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  defect_id       bigint NOT NULL UNIQUE REFERENCES inspection.defect(id),
  prev_defect_id  bigint REFERENCES inspection.defect(id),
  status          varchar(8) NOT NULL CHECK (status IN ('NEW','EXISTING')),
  distance_mm     real,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE inspection.grade_result (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checkpoint_id  varchar(21) NOT NULL UNIQUE,
  grade          char(1)     NOT NULL CHECK (grade IN ('A','B','C','D')),
  rule_version   varchar(32) NOT NULL,
  reasons        jsonb       NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);

